#!/usr/bin/env node

// Usage: node native/tools/embed_fxaa_artifacts.mjs \
//   fragment.spv vertex.dxbc pixel.dxbc

import { readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

function formatBytes(bytes) {
  const lines = [];
  for (let offset = 0; offset < bytes.length; offset += 12) {
    const values = [...bytes.subarray(offset, offset + 12)]
      .map((value) => `0x${value.toString(16).padStart(2, "0")}`);
    lines.push(`  ${values.join(", ")},`);
  }
  return lines.join("\n");
}

function array(name, bytes, { aligned = false, type = "unsigned char" } = {}) {
  const prefix = aligned ? "alignas(4) " : "";
  return `${prefix}inline constexpr ${type} ${name}[] = {\n${formatBytes(bytes)}\n};\n\ninline constexpr std::size_t ${name}_size = sizeof(${name});`;
}

const argumentsList = process.argv.slice(2);
if (argumentsList.length !== 3) {
  throw new Error("Pass fragment SPIR-V, vertex DXBC, and pixel DXBC paths.");
}

const [fragmentSpirv, vertexDxbc, pixelDxbc] =
  await Promise.all(argumentsList.map((path) => readFile(path)));
const toolDirectory = dirname(fileURLToPath(import.meta.url));
const generatedDirectory = resolve(toolDirectory, "../src/render/generated");

const spirvHeader = `#pragma once

#include <cstddef>

// Generated by native/tools/embed_fxaa_artifacts.mjs.
namespace apex::render::generated {

${array("fxaa_fragment_spirv", fragmentSpirv, { aligned: true })}

} // namespace apex::render::generated
`;

const dxbcHeader = `#pragma once

#include <cstddef>
#include <cstdint>

// Generated from shaders/d3d12_fxaa.hlsl with D3DCompile shader model 5.0.
// Embedded by native/tools/embed_fxaa_artifacts.mjs.
// The source and bytecode identities are enforced by a native drift test.
namespace apex::render::generated {

${array("d3d12_fxaa_vertex_dxbc", vertexDxbc, { type: "std::uint8_t" })}

${array("d3d12_fxaa_pixel_dxbc", pixelDxbc, { type: "std::uint8_t" })}

} // namespace apex::render::generated
`;

await Promise.all([
  writeFile(resolve(generatedDirectory, "fxaa_spirv.hpp"), spirvHeader),
  writeFile(resolve(generatedDirectory, "d3d12_fxaa_dxbc.hpp"), dxbcHeader)
]);
